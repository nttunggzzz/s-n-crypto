export async function sendTelegramNotification(
  signal: SetupSignal,
  config?: Partial<TelegramAlertConfig>
): Promise<TelegramMessageResponse> {
  const formattedText = formatTelegramSignalAlert(signal);
  const now = Date.now();

  const botToken = config?.botToken || process.env.TELEGRAM_BOT_TOKEN;
  const chatId = config?.chatId || process.env.TELEGRAM_CHAT_ID;

  if (botToken && chatId && !config?.simulationMode) {
    try {
      const url = `https://api.telegram.org/bot${botToken}/sendMessage`;
      const response = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          chat_id: chatId,
          text: formattedText,
          parse_mode: 'HTML',
          disable_web_page_preview: true
        }),
        signal: AbortSignal.timeout(5000)
      });

      if (response.ok) {
        const json: any = await response.json();
        return {
          success: true,
          messageId: String(json.result?.message_id || `tg-${now}`),
          sentAt: now,
          formattedText,
          destination: `Telegram Chat (${chatId})`
        };
      } else {
        const errText = await response.text();
        return {
          success: false,
          sentAt: now,
          formattedText,
          destination: `Telegram Chat (${chatId})`,
          error: `Telegram API Error (${response.status}): ${errText}`
        };
      }
    } catch (err: any) {
      return {
        success: false,
        sentAt: now,
        formattedText,
        destination: `Telegram Chat (${chatId})`,
        error: err?.message || 'Network error delivering telegram webhook'
      };
    }
  }

  // Simulation mode response
  return {
    success: true,
    messageId: `sim-msg-${Math.floor(Math.random() * 90000 + 10000)}`,
    sentAt: now,
    formattedText,
    destination: 'Telegram Simulation Channel (#alpha-signals)'
  };
}

